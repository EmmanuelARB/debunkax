def build_vectorizer_helpers():
    def word_ngrams(tokens, min_n, max_n):
        if max_n == 1:
            return list(tokens)
        n = len(tokens)
        result = list(tokens) if min_n == 1 else []
        start = 2 if min_n == 1 else min_n
        for k in range(start, min(max_n, n) + 1):
            for i in range(n - k + 1):
                result.append(" ".join(tokens[i : i + k]))
        return result

    def char_ngrams(text, min_n, max_n):
        n = len(text)
        result = list(text) if min_n == 1 else []
        start = 2 if min_n == 1 else min_n
        for k in range(start, min(max_n, n) + 1):
            for i in range(n - k + 1):
                result.append(text[i : i + k])
        return result

    return word_ngrams, char_ngrams


def tfidf(grams, vocab, idf):
    counts = {}
    for g in grams:
        idx = vocab.get(g)
        if idx is not None:
            counts[idx] = counts.get(idx, 0) + 1
    if not counts:
        return {}
    weights = {}
    norm_sq = 0.0
    for idx, count in counts.items():
        value = (1.0 + math.log(count)) * idf[idx]
        weights[idx] = value
        norm_sq += value * value
    if norm_sq == 0.0:
        return {}
    norm = math.sqrt(norm_sq)
    return {idx: value / norm for idx, value in weights.items()}


def score(sentence, export, word_ngrams, char_ngrams):
    text = normalize(sentence)
    tokens = [t for t in text.split(" ") if t]
    word_vec = tfidf(word_ngrams(tokens, *export["word"]["ngram_range"]), export["word"]["vocab"], export["word"]["idf"])
    char_vec = tfidf(char_ngrams(text, *export["char"]["ngram_range"]), export["char"]["vocab"], export["char"]["idf"])
    n_word = len(export["word"]["vocab"])
    dot = export["intercept"]
    coef = export["coef"]
    for idx, value in word_vec.items():
        dot += value * coef[idx]
    for idx, value in char_vec.items():
        dot += value * coef[n_word + idx]
    return 1.0 / (1.0 + math.exp(-dot))


def main():
    with open(EXPORT_PATH, encoding="utf-8") as f:
        export = json.load(f)
    word_ngrams, char_ngrams = build_vectorizer_helpers()

    assert len(SENTENCES) == len(set(SENTENCES)), "duplicate sentence in fixture"

    fixture = {
        "threshold": export["threshold"],
        "cases": [
            {"sentence": s, "probability": score(s, export, word_ngrams, char_ngrams)}
            for s in SENTENCES
        ],
    }
    with open(DEST, "w", encoding="utf-8") as f:
        json.dump(fixture, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"Wrote {DEST} ({len(SENTENCES)} sentences)")


if __name__ == "__main__":
    main()
